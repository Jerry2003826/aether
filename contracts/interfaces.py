"""AETHER interfaces to implement. These are NOT third-party SDK API signatures."""
from typing import Protocol
from reference.models import (
    ArtifactRef, CodingJobRequest, CodingJobResult, GoalContract, ModelRequest,
    ModelResult, OperationIntent, SearchRequest, SearchResult, VerificationResult,
)

class ModelGateway(Protocol):
    async def generate(self, request: ModelRequest) -> ModelResult: ...

class ToolGateway(Protocol):
    async def execute(self, intent: OperationIntent) -> dict: ...
    async def reconcile(self, project_id: str, intent_id: str) -> dict: ...

class CodingExecutor(Protocol):
    async def start(self, request: CodingJobRequest) -> CodingJobResult: ...
    async def get(self, project_id: str, job_id: str) -> CodingJobResult: ...
    async def cancel(self, project_id: str, job_id: str) -> CodingJobResult: ...

class Verifier(Protocol):
    async def verify(self, contract: GoalContract, artifact: ArtifactRef) -> list[VerificationResult]: ...

class Knowledge(Protocol):
    async def search(self, request: SearchRequest) -> SearchResult: ...

class ArtifactStore(Protocol):
    async def put(self, project_id: str, data: bytes, media_type: str) -> ArtifactRef: ...
    async def get(self, project_id: str, artifact_id: str) -> bytes: ...
    async def tombstone(self, project_id: str, artifact_id: str) -> None: ...
